import { apiClient } from "./client";
import type { DeactivationImpact } from "../utils/deactivation";
import type {
  AccountCreate,
  AccountCreated,
  PasswordReset,
  User,
  UsernameAvailability,
  UserUpdate,
} from "../types/user";

// The account-management calls (backend/app/routers/users.py): the
// 系統管理員 and the 教學組長, each seeing only the accounts they may
// manage. apiClient attaches the stored JWT to every request automatically.
// 帳號改版: accounts are never deleted.

// `search`: only the accounts whose 帳號 or 教師姓名 contains it.
export async function list(search: string | null = null): Promise<User[]> {
  const response = await apiClient.get<User[]>("/api/v1/users/", {
    params: search === null || search.trim() === "" ? undefined : { search: search.trim() },
  });
  return response.data;
}

// The password is generated by the backend and mailed to the email.
export async function createAccount(data: AccountCreate): Promise<AccountCreated> {
  const response = await apiClient.post<AccountCreated>("/api/v1/users/", data);
  return response.data;
}

export async function update(userId: number, data: UserUpdate): Promise<User> {
  const response = await apiClient.patch<User>(`/api/v1/users/${userId}`, data);
  return response.data;
}

export async function resetPassword(userId: number, data: PasswordReset): Promise<void> {
  await apiClient.patch(`/api/v1/users/${userId}/password`, data);
}

// 教學組長's 離校: the 一般老師 becomes 無所屬學校.
export async function leaveSchool(userId: number): Promise<User> {
  const response = await apiClient.post<User>(`/api/v1/users/${userId}/leave-school`);
  return response.data;
}

// 新增帳號 checks the email while it is typed (unique across schools).
export async function isUsernameAvailable(username: string): Promise<boolean> {
  const response = await apiClient.get<UsernameAvailability>("/api/v1/users/username-available", {
    params: { username },
  });
  return response.data.available;
}

// What 停用 would touch (counts for DeactivateConfirmDialog).
export async function deactivationImpact(id: number): Promise<DeactivationImpact> {
  const response = await apiClient.get<DeactivationImpact>(`/api/v1/users/${id}/deactivation-impact`);
  return response.data;
}
